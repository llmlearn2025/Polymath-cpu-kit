"""Datasets as objects of their own.

  datasets/<id>/manifest.json   name, topic, source (generate | compose | import), mode, playbook, options, status,
                                counts, report, packs trained from it, edit versions
                base.jsonl      the items as generated (regenerated by Continue)
                tests_base.jsonl
                edits.jsonl     the user's edits as operations (delete / edit / add / move), applied on top of base
                train.jsonl     base + edits: what training reads
                tests.jsonl

Edits are kept as operations keyed by an item's hash, so Continue (which rewrites base from the unit cache) never
undoes them. A version is a group of operations; reverting drops the operations after it.

UnitCache: every generation call's output is cached by a content key (topic/units/<key>.json), so running the same
options again — Continue — only does the units that are missing or failed. Regenerate uses a new salt.
"""
from __future__ import annotations

import hashlib
import json
import re
import secrets
import shutil
import time
from collections import Counter
from pathlib import Path

from packsmith.packs import store


# ---------------------------------------------------------------- unit cache
class UnitCache:
    def __init__(self, d: Path | None, salt: str = ""):
        self.d, self.salt = (Path(d) if d else None), salt
        self.hits = self.new = self.failed = 0

    def key(self, *parts) -> str:
        return hashlib.sha1(json.dumps([self.salt, *parts], sort_keys=True, ensure_ascii=False, default=str).encode()).hexdigest()[:20]

    def get(self, key: str):
        if not self.d:
            return None
        p = self.d / f"{key}.json"
        if p.exists():
            self.hits += 1
            return store.rj(p)
        return None

    def put(self, key: str, value):
        self.new += 1
        if self.d:
            store.wj(self.d / f"{key}.json", value)
        return value

    def run(self, key: str, fn):
        """The cached value for key, or fn() stored under it. A failure is counted and re-raised (nothing cached)."""
        v = self.get(key)
        if v is not None:
            return v
        try:
            return self.put(key, fn())
        except Exception:
            self.failed += 1
            raise

    def stats(self) -> dict:
        return {"cached": self.hits, "new": self.new, "failed": self.failed}


NULL = UnitCache(None)


def cache_for(topic_id: str, salt: str = "") -> UnitCache:
    return UnitCache(store.topic_dir(topic_id) / "units", salt)


# ---------------------------------------------------------------- datasets
def ddir(did: str) -> Path:
    return store.data_dir() / "datasets" / did


def _rows(p: Path) -> list[dict]:
    return [json.loads(x) for x in store.rt(p).splitlines() if x.strip()]


def _write_rows(p: Path, rows: list[dict]) -> None:
    store.wt(p, "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))


def item_hash(x: dict) -> str:
    return hashlib.sha1(f"{x.get('kind', '')}|{x.get('text', x.get('question', ''))}|{x.get('copy', 0)}".encode()).hexdigest()[:16]


def manifest(did: str) -> dict:
    m = store.rj(ddir(did) / "manifest.json")
    if not m:
        raise KeyError(f"no dataset {did}")
    return m


def save_manifest(m: dict) -> dict:
    m["updated"] = time.strftime("%Y-%m-%d %H:%M")
    store.wj(ddir(m["id"]) / "manifest.json", m)
    return m


def create(name: str, topic: str = "", source: str = "generate", **meta) -> dict:
    did = store.new_id(name or "dataset")
    m = {"id": did, "name": name or did, "topic": topic, "source": source, "created": time.strftime("%Y-%m-%d %H:%M"),
         "status": "running", "salt": secrets.token_hex(4), "counts": {}, "report": {}, "packs": [], "versions": [], **meta}
    ddir(did).mkdir(parents=True, exist_ok=True)
    return save_manifest(m)


def list_all(topic: str | None = None) -> list[dict]:
    d = store.data_dir() / "datasets"
    d.mkdir(parents=True, exist_ok=True)
    out = []
    for p in sorted(d.iterdir()):
        m = store.rj(p / "manifest.json")
        if m and (topic is None or m.get("topic") == topic):
            out.append(m)
    return sorted(out, key=lambda m: m.get("created", ""), reverse=True)


def write_base(did: str, train: list[dict], tests: list[dict], report: dict, status: str = "complete") -> dict:
    d = ddir(did)
    for x in train:
        x.setdefault("h", item_hash(x))
    for x in tests:
        x.setdefault("h", item_hash(x))
    _write_rows(d / "base.jsonl", train)
    _write_rows(d / "tests_base.jsonl", tests)
    m = manifest(did)
    m.update(status=status, report={k: v for k, v in report.items() if k != "options"})
    save_manifest(m)
    return materialize(did)


def edits(did: str) -> list[dict]:
    return _rows(ddir(did) / "edits.jsonl")


def materialize(did: str) -> dict:
    """train/tests = base + edits (in order)."""
    d = ddir(did)
    train, tests = _rows(d / "base.jsonl"), _rows(d / "tests_base.jsonl")
    for op in edits(did):
        train, tests = _apply(op, train, tests)
    _write_rows(d / "train.jsonl", train)
    _write_rows(d / "tests.jsonl", tests)
    m = manifest(did)
    m["counts"] = {"train": len(train), "tests": len(tests), "by_kind": dict(Counter(x.get("kind", "") for x in train)),
                   "edits": len(edits(did))}
    save_manifest(m)
    return m


def _apply(op: dict, train: list, tests: list) -> tuple[list, list]:
    hs = set(op.get("h") or [])
    kind = op["op"]
    if kind == "delete":
        return [x for x in train if x["h"] not in hs], [x for x in tests if x["h"] not in hs]
    if kind == "edit":                                   # {h: [..], text?/kind?/question?/expected?} or replace map
        rep = op.get("set") or {}
        def upd(x):
            if x["h"] in hs:
                x = {**x, **rep, "h": x["h"], "edited": True}
            return x
        return [upd(x) for x in train], [upd(x) for x in tests]
    if kind == "replace":                                # {h, find, repl, regex, case}
        rx = _rx(op["find"], op.get("regex"), op.get("case"))
        def rp(x):
            if x["h"] in hs:
                y = dict(x)
                for f in ("text", "question", "expected"):
                    if isinstance(y.get(f), str):
                        y[f] = rx.sub(op.get("repl", "") if op.get("regex") else op.get("repl", "").replace("\\", "\\\\"), y[f])
                y["edited"] = True
                return y
            return x
        return [rp(x) for x in train], [rp(x) for x in tests]
    if kind == "add":
        x = dict(op["item"])
        x.setdefault("h", "u" + item_hash(x))
        if op.get("to") == "tests":
            return train, tests + [x]
        return train + [x], tests
    if kind == "move":                                   # train → tests or back
        if op.get("to") == "tests":
            moved = [x for x in train if x["h"] in hs]
            return ([x for x in train if x["h"] not in hs],
                    tests + [{"question": x.get("text", ""), "expected": "", **x} for x in moved])
        moved = [x for x in tests if x["h"] in hs]
        return train + [{"text": x.get("text") or f"Question: {x.get('question', '')}\nAnswer: {x.get('expected', '')}",
                         "kind": x.get("kind", "test"), "h": x["h"]} for x in moved], [x for x in tests if x["h"] not in hs]
    if kind == "mark":
        def mk(x):
            return {**x, "reviewed": op.get("value", True)} if x["h"] in hs else x
        return [mk(x) for x in train], [mk(x) for x in tests]
    return train, tests


def _rx(find: str, regex: bool = False, case: bool = False):
    return re.compile(find if regex else re.escape(find), 0 if case else re.I)


def apply_ops(did: str, ops: list[dict], note: str = "") -> dict:
    """Append a version (a group of operations) and rebuild train/tests."""
    m = manifest(did)
    if m.get("status") == "running":
        raise ValueError("the dataset is being generated; wait or pause it first")
    n0 = len(edits(did))
    with (ddir(did) / "edits.jsonl").open("a", encoding="utf-8") as f:
        for op in ops:
            f.write(json.dumps({**op, "time": time.strftime("%Y-%m-%d %H:%M:%S")}, ensure_ascii=False) + "\n")
    m["versions"] = (m.get("versions") or []) + [{"v": len(m.get("versions") or []) + 1, "ops": [n0, n0 + len(ops)],
                                                   "note": note or ", ".join(sorted({o["op"] for o in ops})),
                                                   "time": time.strftime("%Y-%m-%d %H:%M")}]
    save_manifest(m)
    return materialize(did)


def revert(did: str, version: int) -> dict:
    """Keep versions 1..version (0 = no edits)."""
    m = manifest(did)
    vs = [v for v in (m.get("versions") or []) if v["v"] <= version]
    keep = vs[-1]["ops"][1] if vs else 0
    _write_rows(ddir(did) / "edits.jsonl", edits(did)[:keep])
    m["versions"] = vs
    save_manifest(m)
    return materialize(did)


def load(did: str) -> tuple[list[dict], list[dict]]:
    return _rows(ddir(did) / "train.jsonl"), _rows(ddir(did) / "tests.jsonl")


def train_path(did: str) -> Path:
    return ddir(did) / "train.jsonl"


def tests_path(did: str) -> Path:
    return ddir(did) / "tests.jsonl"


def delete(did: str) -> dict:
    m = manifest(did)
    if m.get("status") == "running":
        raise ValueError("pause or cancel the generation first")
    shutil.rmtree(ddir(did), ignore_errors=True)
    if m.get("topic"):
        try:
            t = store.topic(m["topic"])
            if t.get("current_dataset") == did:
                rest = list_all(m["topic"])
                t["current_dataset"] = rest[0]["id"] if rest else ""
                store.save_topic(t)
                _mirror(m["topic"])
        except KeyError:
            pass
    return {"deleted": did, "packs": m.get("packs", [])}


def rename(did: str, name: str) -> dict:
    m = manifest(did)
    m["name"] = name
    return save_manifest(m)


def set_current(topic_id: str, did: str) -> None:
    t = store.topic(topic_id)
    t["current_dataset"] = did
    store.save_topic(t)
    _mirror(topic_id)


def _mirror(topic_id: str) -> None:
    """topic/dataset/{train,tests}.jsonl mirror the topic's current dataset (older parts of the app read them)."""
    t = store.topic(topic_id)
    d = store.topic_dir(topic_id) / "dataset"
    did = t.get("current_dataset")
    if did and ddir(did).exists():
        d.mkdir(parents=True, exist_ok=True)
        shutil.copy(train_path(did), d / "train.jsonl")
        shutil.copy(tests_path(did), d / "tests.jsonl")
        store.wj(d / "report.json", {**(manifest(did).get("report") or {}), "dataset": did})
    else:
        for f in ("train.jsonl", "tests.jsonl", "report.json"):
            (d / f).unlink(missing_ok=True)


def add_pack(did: str, pack: str) -> None:
    try:
        m = manifest(did)
    except KeyError:
        return
    m["packs"] = sorted(set(m.get("packs", [])) | {pack})
    save_manifest(m)


# ---------------------------------------------------------------- browsing / searching (the editor)
def query(did: str, part: str = "train", q: str = "", regex: bool = False, case: bool = False, kind: str = "",
          check: str = "", source: str = "", min_len: int = 0, max_len: int = 0, has_numbers: bool = False,
          edited: str = "", offset: int = 0, limit: int = 100) -> dict:
    rows = load(did)[0 if part == "train" else 1]
    try:
        rx = _rx(q, regex, case) if q else None
    except re.error as e:
        raise ValueError(f"bad pattern: {e}")
    def txt(x):
        return " ".join(str(x.get(f, "")) for f in ("text", "question", "expected"))
    out = []
    for x in rows:
        t = txt(x)
        if rx and not rx.search(t):
            continue
        if kind and x.get("kind", "") != kind:
            continue
        if check and check not in str(x.get("check", "")) + str(x.get("ref", "")):
            continue
        if source and source.lower() not in (str(x.get("source", "")) + str(x.get("doc", "")) + str(x.get("page", ""))).lower():
            continue
        if min_len and len(t) < min_len or max_len and len(t) > max_len:
            continue
        if has_numbers and not re.search(r"\d", t):
            continue
        if edited == "edited" and not x.get("edited") or edited == "reviewed" and not x.get("reviewed") \
                or edited == "unreviewed" and x.get("reviewed"):
            continue
        out.append(x)
    kinds = dict(Counter(x.get("kind", "") for x in rows))
    return {"total": len(rows), "matches": len(out), "hashes": [x["h"] for x in out], "items": out[offset:offset + limit],
            "kinds": kinds}


def preview_replace(did: str, hashes: list[str], find: str, repl: str, regex: bool = False, case: bool = False,
                    part: str = "train", limit: int = 50) -> dict:
    rows = load(did)[0 if part == "train" else 1]
    try:
        rx = _rx(find, regex, case)
    except re.error as e:
        raise ValueError(f"bad pattern: {e}")
    hs, changes, n, changed = set(hashes), [], 0, set()
    for x in rows:
        if x["h"] not in hs:
            continue
        for f in ("text", "question", "expected"):
            v = x.get(f)
            if isinstance(v, str) and rx.search(v):
                new = rx.sub(repl if regex else repl.replace("\\", "\\\\"), v)
                n += len(rx.findall(v))
                changed.add(x["h"])
                if len(changes) < limit:
                    changes.append({"h": x["h"], "field": f, "before": v, "after": new})
    return {"items": len(changed), "replacements": n, "changes": changes}


def adopt_legacy() -> int:
    """Datasets made before datasets were objects (topic/dataset/train.jsonl with no current_dataset) become datasets,
    so they show in the Datasets tab, Composer and Train. Compositions built from topics are adopted the same way."""
    n = 0
    for tm in store.list_topics():
        d = store.topic_dir(tm["id"]) / "dataset"
        if tm.get("current_dataset") or not (d / "train.jsonl").exists():
            continue
        rep = store.rj(d / "report.json", {}) or {}
        m = create(f"{tm.get('name', tm['id'])} · earlier dataset", tm["id"], "generate", mode=rep.get("mode", "reasoning"),
                   playbook=rep.get("playbook") or "", options=rep.get("options") or {}, model="")
        write_base(m["id"], _rows(d / "train.jsonl"), _rows(d / "tests.jsonl"), rep)
        t = store.topic(tm["id"])
        t["current_dataset"] = m["id"]
        store.save_topic(t)
        n += 1
    for c in store.list_compositions():
        d = store.data_dir() / "compositions" / c["id"] / "dataset"
        if c.get("dataset") or not (d / "train.jsonl").exists():
            continue
        m = create(c.get("name") or c["id"], "", "compose", mode="composed", composition=c["id"])
        write_base(m["id"], _rows(d / "train.jsonl"), _rows(d / "tests.jsonl"), c.get("built") or {})
        c["dataset"] = m["id"]
        store.save_composition(c)
        n += 1
    return n
